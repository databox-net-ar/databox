--
-- Contexto: la serie venia cargada hasta el 2025-12-13 y quedo cortada. Este
-- backfill tapa el hueco de 175 dias habiles (2025-12-15 .. 2026-08-14). A partir de
-- aca la fila de cada dia la escribe el job `dolarhoy_cotizacion_actualizar`
-- (cloud/jobs/dolarhoy_cotizacion_actualizar.php, `0 7 * * 1-5`).
--
-- FUENTE DE LOS DATOS
-- api.argentinadatos.com/v1/cotizaciones/dolares/oficial -- misma serie que
-- publica dolarhoy.com. Validada antes de generar este archivo: de las 346
-- fechas de 2025 que ya tenia la tabla, las 346 coinciden exactamente en
-- compra y venta con la API (0 diferencias).
--
-- DOS FILAS NO SALEN DE ESA API
--   * 2026-08-06 -> 1470.00 / 1520.00. La fuente no scrapeo ese dia (le falta
--     tambien blue, mep, ccl, mayorista y tarjeta, o sea es un hueco del
--     scraper y no un dia sin mercado). Se toma el valor del 2026-08-05 y del
--     2026-08-07, que son identicos entre si -- el oficial no se movio en esa
--     ventana. VALOR INFERIDO, no verificado contra una publicacion del dia.
--   * 2026-08-14 -> 1465.00 / 1515.00. La API llega hasta el 2026-08-13; este
--     valor se scrapeo en vivo de dolarhoy.com el mismo 2026-08-14.
--
-- ALCANCE: solo lunes a viernes. El historico previo al 2025-12-14 tiene una
-- fila por dia corrido (fines de semana incluidos); de aca en adelante la serie
-- queda solo con dias habiles, alineada con la cadencia del job. Los feriados
-- que caen lun-vie se cargan con el valor que publico la fuente ese dia.
--
-- Idempotente: se materializa el lote en una tabla temporal y se insertan solo
-- las fechas que todavia no existen, asi una re-corrida no duplica filas
-- (`dolarhoy_cotizaciones.fecha` no tiene UNIQUE, no alcanza con INSERT IGNORE).
-- Requiere que ya haya corrido
-- 20260814_1300_clonar_dolarhoycotizaciones_a_dolarhoy_cotizaciones.sql.
--
-- Rango de venta en el lote: 1380 .. 1520.

